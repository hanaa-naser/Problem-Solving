    private void btneqlActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btneqlActionPerformed
        // TODO add your handling code here:
        num2=Integer.parseInt(result.getText());
        double rus= 0;
        switch (op) {
            case "+":
                rus=num1+num2;
                break;
            case "-":
                rus=num1-num2;
                break;
                case "*":
                rus=num1*num2;
                break;
                case "/":
                    if(num2==0){
                    result.setText("error");
                    }
                    else{
                    rus=num1/num2;
                    
                    }
                
                break;
             
        }
       result.setText(String.valueOf(rus));
        
    }//GEN-LAST:event_btneqlActionPerformed

